// Bundles tasks/public into a JS module the portal worker serves directly,
// the same way the portal ships its own UI (no separate asset upload needed).
//
// Site audit (10 Nov 2026): the program and style files are served under a name that carries a fingerprint of their
// content ("/__tasks/app-0123456789ab.js"). A changed file gets a new name, so the browser may keep each one for good
// (portal-proposal/src/worker.mjs KEEP_FOREVER) instead of asking the site about it on every visit. The page itself
// (/tasks.html) is never kept and always names the current files. Source files keep their plain names.
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const src = new URL('../public/', import.meta.url);
const target = new URL('../dist/ui-assets.mjs', import.meta.url);
const types = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8' };
const sha = (text) => createHash('sha256').update(text).digest('hex');
const extOf = (name) => name.slice(name.lastIndexOf('.'));

/** The module text for dist/ui-assets.mjs, built from tasks/public as it is now. */
export async function buildUiModule() {
  const files = {};
  for (const name of (await readdir(src)).sort()) if (types[extOf(name)]) files[name] = await readFile(new URL(name, src), 'utf8');
  const page = 'index.html', named = {}; // source name -> fingerprinted name
  const imports = (name) => extOf(name) === '.js' ? Object.keys(files).filter((other) => other !== name && files[name].includes(`'./${other}'`)) : [];
  // A file that imports another gets its fingerprint after that one (its own text names the other's fingerprinted name).
  const pending = Object.keys(files).filter((name) => name !== page);
  while (pending.length) {
    const i = pending.findIndex((name) => imports(name).every((dep) => named[dep]));
    if (i < 0) throw new Error('task UI: files import each other in a circle');
    const [name] = pending.splice(i, 1);
    for (const dep of imports(name)) files[name] = files[name].replaceAll(`'./${dep}'`, `'./${named[dep]}'`);
    const ext = extOf(name);
    named[name] = `${name.slice(0, -ext.length)}-${sha(files[name]).slice(0, 12)}${ext}`;
  }
  for (const [name, to] of Object.entries(named)) files[page] = files[page].replaceAll(`/__tasks/${name}`, `/__tasks/${to}`);
  const out = {};
  for (const [name, body] of Object.entries(files)) {
    out[name === page ? '/tasks.html' : `/__tasks/${named[name]}`] = { type: types[extOf(name)], body, etag: sha(body).slice(0, 16) };
  }
  return `// Generated by scripts/build-ui-module.mjs. Do not edit.\nexport default ${JSON.stringify(out)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await buildUiModule();
  await mkdir(new URL('../dist/', import.meta.url), { recursive: true });
  await writeFile(target, text);
  console.log('task UI module:', Object.keys((await import(`${target.href}?${Date.now()}`)).default).join(', '));
}
